def _sm(x): x = min(1.0, max(0.0, x)); return x * x * (3 - 2 * x)

PLAN = [4879.4, 12103.6, 6779.0, 139820.0, 116460.0, 50724.0, 49244.0]
ARRIVE = [15.06, 16.35, 17.27, 18.34, 19.28, 19.85, 20.59]

def DRAW(img, t, g):
    big = g['f_tick']; small = g['f_end3']; SUN = g['SUN']
    def show(a, b, val, label, col=SUN, y=330):
        al = g['fade'](t, a, b, 0.35)
        if al > 0:
            g['draw_block'](img, val, big, y, al, fill=col)
            g['draw_block'](img, label, small, y + 100, al, fill=(200, 208, 224))
    sp = lambda n: f'{int(round(n)):,}'.replace(',', ' ')
    show(4.6, 9.7, '3 475 км', 'діаметр Місяця — майже вчетверо\nменший за Землю')
