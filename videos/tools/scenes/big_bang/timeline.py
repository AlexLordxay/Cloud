LEAD = 0.3


def find(prefix, out):
    for p in out:
        if p['text'].startswith(prefix): return p
    raise KeyError(prefix)


def build():
    out, t, prev = [], 0.0, 0.0
    for i, (a, b, txt, _) in enumerate(P):
        gap = (a - prev if 0 <= a - prev < 1.5 else NORMAL_GAP) if i else 0.0
        extra = next((v for k, v in PAUSES.items() if txt.startswith(k)), 0.0)
        t += gap + extra
        out.append(dict(i=i, src=[a, b], pause=round(gap + extra, 2), t0=round(t, 3), t1=round(t + b - a, 3), text=txt))
        t += b - a; prev = b
    dur = round(t + TAIL, 2)
    acts = [dict(name=n, t0=0.0 if k == 0 else round(find(p, out)['t0'] - find(p, out)['pause'] + 0.3, 2))
            for k, (n, p) in enumerate(ACTS)]
    shots = []
    for nm, pfx, off in SHOTS:
        p = find(pfx, out)
        if p['i'] == 0: t0 = 0.0
        elif off is None: t0 = p['t0'] - LEAD
        elif off == 'pause': t0 = p['t0'] - p['pause'] + 0.3
        else: t0 = p['t0'] + off
        shots.append(dict(name=nm, t0=round(t0, 2)))
    for k, s in enumerate(shots):
        s['t1'] = shots[k + 1]['t0'] if k + 1 < len(shots) else dur
        s['dur'] = round(s['t1'] - s['t0'], 2)
    return dict(voice='voice_all.mp3', duration=dur, phrases=out, acts=acts, shots=shots)


def mmss(x): return f'{int(x // 60)}:{x % 60:05.2f}'


